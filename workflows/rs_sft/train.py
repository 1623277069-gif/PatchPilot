"""QAT-lineage QLoRA: one step -> save/reload -> official loader -> full run.

CT INT4 and bitsandbytes NF4 are different formats. We never pretend that
passing BitsAndBytesConfig to the packed CT checkpoint is valid. The explicit
prepare stage dequantizes the exact local QAT checkpoint to dense weights;
QLoRA then loads that derived checkpoint in NF4. This adds quantization error,
so the final adapter MUST pass loading/effect checks on the original CT base.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
from common import ROOT, HF_MODEL, digest, model_identity, read_json, rows, write_json


def cuda():
    import torch
    if not torch.cuda.is_available():
        raise RuntimeError('CUDA required; no model training or paid fallback attempted')
    if not torch.cuda.is_bf16_supported():
        raise RuntimeError('This verified configuration requires BF16 CUDA hardware; do not silently switch precision')
    return torch


def prepare(args):
    cuda()
    identity = model_identity(args.model_dir)
    destination = args.dense_dir
    if destination.exists():
        raise FileExistsError('Dense derived checkpoint exists; verify provenance instead of overwriting')
    # This exact, memory-intensive conversion is explicit and never performed
    # on the user's 8 GB Mac. Avoid claiming Kaggle resources will suffice.
    if shutil.disk_usage(destination.parent).free < 75 * 2**30:
        raise RuntimeError('QAT dequantization requires at least 75 GiB free scratch disk')
    meminfo = Path('/proc/meminfo')
    if not meminfo.exists():
        raise RuntimeError('Linux memory preflight unavailable; QAT conversion not started')
    available = next((int(line.split()[1]) * 1024 for line in meminfo.read_text().splitlines()
                      if line.startswith('MemAvailable:')), 0)
    if available < 72 * 2**30:
        raise RuntimeError('Conservative CT->BF16 conversion needs 72 GiB available host RAM; stop without replacing the base')
    from transformers import Gemma4ForConditionalGeneration, CompressedTensorsConfig, AutoTokenizer
    temporary = destination.with_name(destination.name + '.partial')
    temporary.mkdir(parents=True, exist_ok=False)
    model = Gemma4ForConditionalGeneration.from_pretrained(
        args.model_dir, local_files_only=True, device_map='cpu', dtype='bfloat16',
        quantization_config=CompressedTensorsConfig(dequantize=True))
    if hasattr(model.config, 'quantization_config'):
        del model.config.quantization_config
    model.save_pretrained(temporary, safe_serialization=True, max_shard_size='4GB')
    AutoTokenizer.from_pretrained(args.model_dir, local_files_only=True).save_pretrained(temporary)
    dense_hashes = {p.name: file_sha(p) for p in sorted(temporary.glob('*')) if p.is_file()}
    write_json(temporary / 'qat_origin.json', {'source': identity,
              'conversion': 'exact CT QAT -> dequantized BF16; next stage NF4', 'files': dense_hashes})
    temporary.rename(destination)


def file_sha(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as f:
        for block in iter(lambda: f.read(8 * 1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def train(args):
    scope = read_json(ROOT / 'configs/experiment.json').get('execution_scope', {})
    if args.stage == 'formal' and not scope.get('formal_training_allowed', False):
        raise RuntimeError('Formal training is disabled by the current single-task/single-step scope')
    torch = cuda()
    from transformers import Gemma4ForConditionalGeneration, BitsAndBytesConfig, Trainer, TrainingArguments
    from peft import LoraConfig, get_peft_model, prepare_model_for_kbit_training, PeftModel
    identity = model_identity(args.model_dir)
    origin = read_json(args.dense_dir / 'qat_origin.json')
    if origin['source']['fingerprint'] != identity['fingerprint']:
        raise ValueError('Training checkpoint not derived from the exact QAT base')
    for name, expected in origin['files'].items():
        if file_sha(args.dense_dir / name) != expected:
            raise ValueError('Derived dense checkpoint changed')
    data_path = args.data.resolve()
    if not data_path.is_relative_to(ROOT / 'data'):
        raise ValueError('Training data must remain inside the independent experiment data directory')
    dataset = rows(data_path)
    if not dataset:
        raise RuntimeError('No verified successful SFT examples')
    split = read_json(ROOT / 'data/split.json')
    for sample in dataset:
        if sample['task_id'] not in split['train_ids'] or sample['task_id'] in split['validation_ids']:
            raise ValueError('Validation task in training data')
        if sample['provenance']['base_fingerprint'] != identity['fingerprint']:
            raise ValueError('SFT samples generated by a different base')
        if len(sample['input_ids']) != len(sample['labels']) or not any(x != -100 for x in sample['labels']):
            raise ValueError('Invalid loss labels')
    data_hash = file_sha(data_path)
    destination = ROOT / 'models' / ('smoke' if args.stage == 'smoke' else 'formal')
    if args.stage == 'formal':
        smoke = read_json(ROOT / 'models/smoke/training_receipt.json')
        loading = read_json(ROOT / 'models/smoke/official_load_receipt.json')
        if (not smoke.get('passed') or not loading.get('passed')
                or smoke['data_sha256'] != data_hash
                or smoke['base_fingerprint'] != identity['fingerprint']
                or loading['base_fingerprint'] != identity['fingerprint']):
            raise RuntimeError('Single-step + official adapter loading gates must pass first')
    run_identity = {'base_fingerprint': identity['fingerprint'], 'data_sha256': data_hash,
                    'split_sha256': split['freeze_sha256'], 'rank': 8, 'alpha': 16,
                    'lr': 1e-4, 'max_steps': 1 if args.stage == 'smoke' else args.steps,
                    'seed': 20261117, 'quantization': 'NF4 derived from CT QAT'}
    destination.mkdir(parents=True, exist_ok=True)
    identity_path = destination / 'run_identity.json'
    if identity_path.exists() and read_json(identity_path) != run_identity:
        raise ValueError('Resume training configuration changed')
    write_json(identity_path, run_identity)
    bnb = BitsAndBytesConfig(load_in_4bit=True, bnb_4bit_quant_type='nf4',
                            bnb_4bit_use_double_quant=True, bnb_4bit_compute_dtype=torch.bfloat16)
    model = Gemma4ForConditionalGeneration.from_pretrained(
        args.dense_dir, local_files_only=True, device_map='auto', dtype=torch.bfloat16,
        quantization_config=bnb)
    if any(str(v) in {'cpu', 'disk'} for v in getattr(model, 'hf_device_map', {}).values()):
        raise RuntimeError('Training model did not fit GPUs; no CPU/disk training fallback')
    model = prepare_model_for_kbit_training(model, use_gradient_checkpointing=True)
    targets = [name for name, module in model.named_modules()
               if '.language_model.' in '.' + name and name.endswith(('.q_proj', '.v_proj'))]
    if not targets:
        raise RuntimeError('No text-only LoRA target modules found; inspect installed Gemma4 implementation')
    model = get_peft_model(model, LoraConfig(r=8, lora_alpha=16, target_modules=targets,
                                          lora_dropout=0.0, bias='none', task_type='CAUSAL_LM'))
    model.config.use_cache = False
    # No packing, no accidental all-token labels, no data collator relabeling.
    def collate(batch):
        length = max(len(x['input_ids']) for x in batch)
        return {key: torch.tensor([x[key] + [padding] * (length - len(x[key])) for x in batch])
                for key, padding in [('input_ids', 0), ('attention_mask', 0), ('labels', -100)]}
    training = TrainingArguments(output_dir=str(destination / 'checkpoints'),
        max_steps=run_identity['max_steps'], per_device_train_batch_size=1,
        gradient_accumulation_steps=1 if args.stage == 'smoke' else 4,
        learning_rate=1e-4, bf16=True, fp16=False, gradient_checkpointing=True,
        logging_steps=1, save_steps=1 if args.stage == 'smoke' else 10,
        save_total_limit=2, report_to=[], seed=20261117, data_seed=20261117,
        remove_unused_columns=False)
    compact = [{k: row[k] for k in ['input_ids', 'attention_mask', 'labels']} for row in dataset]
    trainer = Trainer(model=model, args=training, train_dataset=compact, data_collator=collate)
    checkpoints = sorted((destination / 'checkpoints').glob('checkpoint-*'),
                         key=lambda p: int(p.name.rsplit('-', 1)[1]))
    trainer.train(resume_from_checkpoint=str(checkpoints[-1]) if checkpoints else None)
    write_json(destination / 'training_log.json', trainer.state.log_history)
    model.save_pretrained(destination, safe_serialization=True)
    # Save metadata against the exact competition base, never the ordinary IT model.
    cfg = read_json(destination / 'adapter_config.json')
    cfg['base_model_name_or_path'] = HF_MODEL
    write_json(destination / 'adapter_config.json', cfg)
    probe = collate(compact[:1])
    device = model.get_input_embeddings().weight.device
    probe = {k: v.to(device) for k, v in probe.items() if k != 'labels'}
    # Probe only a short prefix to bound evaluation memory, preserving original IDs.
    probe = {k: v[:, :128] for k, v in probe.items()}
    model.eval()
    with torch.no_grad():
        expected = model(**probe).logits[:, -1].float().cpu()
        with model.disable_adapter():
            base = model(**probe).logits[:, -1].float().cpu()
    delta = (expected - base).abs().max().item()
    if not torch.isfinite(expected).all() or delta <= 1e-6:
        raise RuntimeError('Adapter has no measurable effect after training')
    # Unload adapter only, keeping the same quantized base for numerical reload check.
    bare = model.unload()
    reloaded = PeftModel.from_pretrained(bare, destination, is_trainable=False, local_files_only=True)
    reloaded.eval()
    with torch.no_grad():
        actual = reloaded(**probe).logits[:, -1].float().cpu()
    reload_difference = (expected - actual).abs().max().item()
    if not torch.allclose(expected, actual, atol=1e-3, rtol=1e-3):
        raise RuntimeError('Saved adapter numerical reload mismatch')
    write_json(destination / 'training_receipt.json', {**run_identity, 'passed': True,
               'completed_steps': trainer.state.global_step, 'base_delta_max': delta,
               'reload_difference_max': reload_difference,
               'adapter_sha256': file_sha(destination / 'adapter_model.safetensors'),
               'official_ct_vllm_compatible': False})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('stage', choices=['prepare', 'smoke', 'formal'])
    parser.add_argument('--model-dir', type=Path, required=True)
    parser.add_argument('--dense-dir', type=Path, default=ROOT / 'models/qat-derived-bf16')
    parser.add_argument('--data', type=Path, default=ROOT / 'data/sft.jsonl',
                        help='Verified SFT export; single-task smoke may use data/one_task_mask_smoke.jsonl')
    parser.add_argument('--steps', type=int, default=30)
    args = parser.parse_args()
    if args.steps < 1:
        parser.error('steps must be positive')
    if args.stage == 'prepare':
        prepare(args)
    else:
        train(args)


if __name__ == '__main__':
    main()
